# RPC란?
# RPC(Remote Procedure Call)은 네트워크 상에서 다른 컴퓨터에 있는 함수를 호출하는 프로토콜
# RPC를 사용하면 개발자는 마치 로컬에서 함수를 호출하는 것처럼 원격 시스템의 함수를 호출할 수 있음
# 이는 분산 시스템에서 서로 다른 컴퓨터 간의 통신을 쉽게 만들어줌

# RPC의 주요 특징
# 1. 추상화: RPC는 네트워크 통신의 복잡성을 숨기고, 개발자가 원격 함수를 로컬 함수처럼 사용할 수 있도록 추상화함
# 2. 언어 독립성: RPC는 다양한 프로그래밍 언어에서 사용할 수 있도록 설계됨. 
#   - 예를 들어, Python에서 작성된 클라이언트가 Java로 작성된 서버의 함수를 호출할 수 있음
# 3. 동기 및 비동기 호출: RPC는 동기 호출과 비동기 호출을 모두 지원함. 
#   - 동기 호출은 함수가 완료될 때까지 기다리는 반면, 비동기 호출은 함수가 완료될 때까지 기다리지 않고 다른 작업을 계속할 수 있음


# JSON-RPC란?
# JSON-RPC는 RPC 프로토콜의 한 형태로, JSON(JavaScript Object Notation)을 사용하여 원격 함수를 호출하는 방식

# JSON-RPC의 주요 특징
# 1. JSON 기반: JSON-RPC는 JSON 형식을 사용하여 요청과 응답을 표현함.
# 2. 간단한 구조: JSON-RPC는 간단한 구조를 가지고 있어 구현이 용이함.
# 3. HTTP 및 WebSocket 지원: JSON-RPC는 HTTP와 WebSocket과 같은 다양한 전송 프로토콜을 지원함.
# 4. 언어 독립성: JSON-RPC는 다양한 프로그래밍 언어에서 사용할 수 있도록 설계됨.

# MCP에서 JSON-RPC는 클라이언트와 서버 간의 통신을 위해 사용될 수 있음.
# 클라이언트는 JSON-RPC를 사용하여 서버에 요청을 보내고,
# 서버는 JSON-RPC를 사용하여 클라이언트의 요청에 응답할 수 있음.

# requests 메시지에 반드시 들어가야 하는것
# 1. jsonrpc: "2.0" - JSON-RPC 버전
# 2. method: 호출하려는 원격 함수의 이름
# 3. params: 원격 함수에 전달할 매개변수 (선택적)
# 4. id: 요청을 식별하기 위한 고유한 식별자 (선택적)

# responses 메시지에 반드시 들어가야 하는것
# 1. jsonrpc: "2.0" - JSON-RPC 버전
# 2. result: 원격 함수 호출의 결과 (성공한 경우)
# 3. error: 원격 함수 호출 중 발생한 오류에 대한 정보 (실패한 경우)
# 4. id: 요청과 응답을 매칭하기 위한 고유한 식별자 (요청과 동일해야 함)

# notification 메시지란?
# notification 메시지는 클라이언트가 서버에 요청을 보내지만, 서버로부터 응답을 기대하지 않는 메시지
# notification 메시지는 일방향 통신에 사용되며,
# 클라이언트가 서버에 정보를 전달하거나 특정 작업을 트리거하는 데 사용될 수 있음

# notification 메시지에 반드시 들어가야 하는것
# 1. jsonrpc: "2.0" - JSON-RPC 버전
# 2. method: 호출하려는 원격 함수의 이름
# 3. params: 원격 함수에 전달할 매개변수 (선택적)
# 4. id: notification 메시지에는 id 필드가 포함되지 않음 (요청과 응답을 매칭할 필요가 없기 때문)

# duscovery 메시지란?
# discovery 메시지는 클라이언트가 서버에 자신의 존재를 알리고, 서버가 클라이언트의 존재를 인식할 수 있도록 하는 메시지
# discovery 메시지는 클라이언트가 서버에 연결할 때 사용되며,
# 서버는 discovery 메시지를 통해 클라이언트의 정보를 수집하고, 클라이언트와의 통신을 관리할 수 있음
# tool list로 discovery 메시지를 보내는 경우, 클라이언트는 서버에 자신이 사용할 수 있는 도구 목록을 전달할 수 있음
# 서버는 이 정보를 사용하여 클라이언트가 어떤 도구를 사용할 수 있는지 이해하고, 
# 클라이언트의 요청에 적절한 도구를 사용할 수 있도록 할 수 있음

